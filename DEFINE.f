!!RL:POSITION OF THE LAST IMAGE

      REAL*8,ALLOCATABLE,DIMENSION(:,:)  :: RL

!!NI:INDEX OF NEIGHBOR:HOW MANY NEIGHBORS FOR EACH ATOM
!!NL:NEIGHBOR LIST:WHAT ARE THE NEIGHBORS

      INTEGER,ALLOCATABLE   :: NI(:),NL(:,:)

!!NL_NEW:TAG:NL NEEDS TO BE UPDATED

      LOGICAL NL_NEW

!!NCELL:NUMBER OF CELLS
!!NMAPS:NUMBER OF MAPS
!!MSIZE:RBOX/CSIZE
!!MSISQ:MSIZE*MSIZE

      INTEGER NCELL,NMAPS,MSIZE,MSISQ

!!PLEASE SEE ORIGINAL ALGORITHM

      INTEGER,ALLOCATABLE   :: LL(:),HH(:),MP(:)

      INTEGER,ALLOCATABLE   :: CP(:,:),IC(:,:,:)

      END MODULE NBLVAR
