      REAL*8,ALLOCATABLE,DIMENSION(:) :: PA,PB,PC,PD,PR

      REAL*8,ALLOCATABLE,DIMENSION(:) :: DA,DB,DC,DD,DR

      REAL*8,ALLOCATABLE,DIMENSION(:) :: EA,EB,EC,ED

